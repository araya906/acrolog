# Downloads the freely licensed reference photos listed in tools/photos.json from Wikimedia Commons
# (500 px wide, a standard Commons thumbnail size) into img/photos/, writes the credits to src/photos.js and the file list into sw.js.
# Usage: powershell -ExecutionPolicy Bypass -File tools/fetch_photos.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$ua = @{ 'User-Agent' = 'AcroLog/1.0 (offline acroyoga tracker; reference photo fetch script)' }
$map = Get-Content (Join-Path $root 'tools/photos.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$dir = Join-Path $root 'img/photos'
New-Item -ItemType Directory -Force $dir | Out-Null
# Wikimedia rate-limits bursts (HTTP 429): pause between requests and back off on errors.
function Invoke-Polite([scriptblock]$call) {
  for ($try = 1; ; $try++) {
    Start-Sleep -Seconds (4 * $try)
    try { return & $call } catch { if ($try -ge 6) { throw } ; Write-Host "  retry ($try)" }
  }
}
# Photos already downloaded are kept (delete img/photos/*.jpg to refresh them all).
$strip = { param($h) ([regex]::Replace([string]$h, '<[^>]+>', '')).Trim() -replace '\s+', ' ' }
$out = [ordered]@{}
$files = @()
foreach ($key in $map.PSObject.Properties.Name) {
  $list = @(); $n = 0
  foreach ($title in $map.$key) {
    $n++
    $u = 'https://commons.wikimedia.org/w/api.php?action=query&format=json&prop=imageinfo&iiprop=url|extmetadata&iiurlwidth=500&titles=' + [uri]::EscapeDataString("File:$title")
    $page = (Invoke-Polite { Invoke-RestMethod -Uri $u -Headers $ua }).query.pages.PSObject.Properties.Value | Select-Object -First 1
    $ii = $page.imageinfo[0]; $m = $ii.extmetadata
    $name = "$key-$n.jpg"
    $file = Join-Path $dir $name
    if (-not (Test-Path $file)) { Invoke-Polite { Invoke-WebRequest -Uri $ii.thumburl -Headers $ua -OutFile $file -UseBasicParsing } | Out-Null }
    $list += [ordered]@{
      src = "img/photos/$name"; title = $title
      author = (& $strip $m.Artist.value); license = $m.LicenseShortName.value; licenseUrl = $m.LicenseUrl.value
      page = $ii.descriptionurl
    }
    $files += "  `"img/photos/$name`","
    "ok $name  ($($m.LicenseShortName.value))"
  }
  $out[$key] = $list
}
$js = "// Generated by tools/fetch_photos.ps1 from Wikimedia Commons. Do not edit by hand.`n// Each photo keeps its own licence; credits are shown under the photo in the app.`nexport const PHOTOS = " + ($out | ConvertTo-Json -Depth 5) + ";`n"
$utf8 = New-Object System.Text.UTF8Encoding $false
[IO.File]::WriteAllText((Join-Path $root 'src/photos.js'), $js, $utf8)
$sw = [IO.File]::ReadAllText((Join-Path $root 'sw.js'))
$sw = [regex]::Replace($sw, '(?s)  // PHOTOS:BEGIN.*?// PHOTOS:END', "  // PHOTOS:BEGIN`n" + ($files -join "`n") + "`n  // PHOTOS:END")
[IO.File]::WriteAllText((Join-Path $root 'sw.js'), $sw, $utf8)
"done: $($files.Count) photos"

# Builds src/acropedia.js (the in-app Acropedia library) from Acropedia's public data file.
# Acropedia (https://www.acrolove.org/acropedia/, AcroLove) lists washing machines with a link to a video of each.
# Only names, families, tags and video links are kept; the videos stay on YouTube/Instagram/Facebook and belong to
# their creators. Usage: powershell -ExecutionPolicy Bypass -File tools/acropedia.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$ua = @{ 'User-Agent' = 'AcroLog/1.0 (offline acroyoga tracker; library build script)' }
$raw = (Invoke-WebRequest -Uri 'https://www.acrolove.org/acropedia/data.json' -Headers $ua -UseBasicParsing).Content
if ($raw -is [byte[]]) { $raw = [Text.Encoding]::UTF8.GetString($raw) }
$skills = ($raw | ConvertFrom-Json).skills

# Short video codes keep the file small: y:<YouTube id>, i:<reel|p>/<Instagram code>, otherwise the full URL
# (tracking parameters such as ?igsh= are dropped).
function Get-Code([string]$u) {
  $m = [regex]::Match($u, '^https?://(?:www\.|m\.)?(?:youtube\.com/(?:watch\?(?:.*&)?v=|shorts/|embed/|live/)|youtu\.be/)([\w-]{11})', 'IgnoreCase')
  if ($m.Success) { return 'y:' + $m.Groups[1].Value }
  $m = [regex]::Match($u, '^https?://(?:www\.|m\.)?instagram\.com/(?:[\w.]+/)?(p|reels?|tv)/([\w-]+)', 'IgnoreCase')
  if ($m.Success) { $k = if ($m.Groups[1].Value.ToLower().StartsWith('reel')) { 'reel' } else { 'p' }; return "i:$k/" + $m.Groups[2].Value }
  if ($u -match '^https?://') {
    $u = $u -replace '#.*$', '' -replace '([?&])(fbclid|mibextid|igsh|igshid|si|utm_[a-z]+|__[a-z_]+)=[^&]*', '$1' -replace '[?&]+$', '' -replace '\?&+', '?'
    return $u
  }
  return ''
}

$rows = foreach ($s in ($skills | Sort-Object { $_.name })) {
  $code = ''
  foreach ($m in $s.media) { $code = Get-Code $m.url; if ($code) { break } }
  $fam = if ($s.familySize -gt 1) { [string]$s.family } else { '' }
  # [id, name, family, tags, video]
  ,@([string]$s.id, [string]$s.name, $fam, (@($s.tags) -join '|'), $code)
}
$json = ($rows | ForEach-Object { ConvertTo-Json -InputObject @($_) -Compress }) -join ",`n"
$js = "// Generated by tools/acropedia.ps1 from Acropedia (https://www.acrolove.org/acropedia/, AcroLove). Do not edit by hand.`n" +
  "// [id, name, family, tags, video]. video: y:<YouTube id> | i:<reel|p>/<Instagram code> | full URL. Videos belong to their creators.`n" +
  "export const AP_BUILT = `"$(Get-Date -Format 'yyyy-MM-dd')`";`nexport const AP = [`n$json`n];`n"
$utf8 = New-Object System.Text.UTF8Encoding $false
[IO.File]::WriteAllText((Join-Path $root 'src/acropedia.js'), $js, $utf8)
"done: $($rows.Count) skills"
